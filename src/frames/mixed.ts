type WindowShape = 'rect' | 'circle' | SculptedMaskRef;
const combinations: WindowShape[][] = [
  ['rect', 'star', 'heart', 'circle'],
  ['heart', 'rect', 'flower', 'star'],
  ['cloud', 'heart', 'rect', 'star'],
  ['rect', 'pebble', 'star', 'heart'],
  ['flower', 'rect', 'heart', 'torn'],
  ['star', 'wave', 'rect', 'flower'],
  ['heart', 'burst', 'cloud', 'rect'],
  ['rect', 'torn', 'star', 'pebble'],
];

function mixedWindows(index: number, format: 'strip' | 'card'): SlotDefinition[] {
  return combinations[index % combinations.length].map((chosen, i) => {
    const shape = format === 'strip' && chosen === 'circle' ? 'flower' : chosen;
    const width = format === 'strip' ? 0.86 : 0.43;
    const rowHeight = format === 'strip' ? 0.18 : 0.35;
    const height = shape === 'circle' ? (width * 1800) / 2700 : rowHeight;
    return {
      id: `p${i + 1}`,
      order: i + 1,
      x: format === 'strip' ? (i % 2 ? 0.09 : 0.05) : i % 2 ? 0.515 : 0.055,
      y:
        (format === 'strip' ? 0.1 + i * 0.2 : 0.115 + Math.floor(i / 2) * 0.395) +
        (rowHeight - height) / 2,
      w: width,
      h: height,
      shape: shape === 'rect' || shape === 'circle' ? shape : 'path',
      ...(shape === 'rect' || shape === 'circle' ? {} : { pathRef: shape }),
      rotationDeg: i % 2 ? 0.7 : -0.7,
      matteColor: '#f2efe9',
    };
  });
}

export const mixedFrames: FrameDefinition[] = themes.map((theme, index) => {
  const [id, name, background, ink, accent, secondary, category, description] = theme;
  const format = index % 3 === 2 ? 'strip' : 'card';
  const result = frame(
    id,
    name,
    format,
    category === 'playful' ? [category] : [category, 'playful'],
    [background, ink, accent, secondary],
    mixedWindows(index, format),
    description,
  );
  const base = `/frames/${id}/v1`;
  return {
    ...result,
    version: 1,
    collection: 'Mixed Moments',
    artwork: { motif: id, edition: index % 11 },
    description: `${description} Empat foto dengan bentuk berbeda dalam satu frame.`,
    layers: { background: `${base}/background.svg`, foreground: `${base}/foreground.svg` },
    thumbnail: `${base}/thumbnail-neutral.png`,
    textAreas: result.textAreas.map((area) =>
      area.id === 'title'
        ? { ...area, x: 0.09, w: 0.82, y: 0.022, h: 0.04, fontSize: format === 'strip' ? 76 : 100 }
        : area.id === 'caption'
          ? { ...area, y: 0.92, h: 0.04, fontSize: 48, minFontSize: 28 }
          : { ...area, y: 0.974, h: 0.018 },
    ),
  };
});

export const mixedIds = mixedFrames.map((frame) => frame.id);
