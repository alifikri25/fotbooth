function windows(layout: string): SlotDefinition[] {
  if (layout === 'trio')
    return [
      slot(1, 0.09, 0.105, 0.82, 0.235),
      slot(2, 0.09, 0.365, 0.82, 0.235),
      slot(3, 0.09, 0.625, 0.82, 0.235),
    ];
  if (layout === 'four')
    return [0, 1, 2, 3].map((i) => slot(i + 1, 0.09, 0.105 + i * 0.19, 0.82, 0.173, 'rect'));
  if (layout === 'duo')
    return [
      slot(1, 0.08, 0.135, 0.4, 0.72, 'roundedRect', { radius: 100 }),
      slot(2, 0.52, 0.135, 0.4, 0.72, 'roundedRect', { radius: 100 }),
    ];
  if (layout === 'grid')
    return [
      slot(1, 0.08, 0.13, 0.4, 0.35, 'rect'),
      slot(2, 0.52, 0.13, 0.4, 0.35, 'rect'),
      slot(3, 0.08, 0.51, 0.4, 0.35, 'rect'),
      slot(4, 0.52, 0.51, 0.4, 0.35, 'rect'),
    ];
  return [
    slot(1, 0.08, 0.13, 0.84, 0.34, 'roundedRect', { radius: 55 }),
    slot(2, 0.08, 0.51, 0.4, 0.35, 'rect'),
    slot(3, 0.52, 0.51, 0.4, 0.35, 'path', { pathRef: 'chamfer' }),
  ];
}
